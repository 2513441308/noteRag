"""查询改写节点的提示词模板.

结合对话历史把含指代的追问改写为自包含的独立检索查询，并向知识库真实
章节术语对齐（术语表由节点从向量库 metadata 聚合后注入）。
"""

from __future__ import annotations

from langchain_core.prompts import ChatPromptTemplate

# 输入变量：
#   glossary - 知识库章节标题术语参考（可能为「（无）」）
#   history  - 节点渲染的历史文本（可能为「（无）」）
#   question - 用户最新问题
# 期望输出：改写后的自包含检索查询，纯文本
REWRITE_PROMPT = ChatPromptTemplate.from_messages(
    [
        (
            "system",
            "你是检索查询改写器。多轮对话中用户的最新问题可能包含「它/这个/上面那个」"
            "等指代表述，无法直接用于知识库检索。\n"
            "请结合对话历史，把最新问题改写为一个语义完整、自包含的检索查询：\n"
            "- 补全指代对象，保留关键实体与技术名词；\n"
            "- 如果最新问题本身已经自包含，原样输出即可；\n"
            "- 只输出改写后的查询文本，不要解释、不要加引号；\n"
            "- 不要回答问题，也不要引入对话历史中未出现的新信息。\n\n"
            "下面是知识库中真实出现的章节/术语路径。改写时若涉及同义或近义概念，"
            "优先向这些用词靠拢（例如用户说「分支判断」、术语表有「条件边」时，"
            "用「条件边」）；但术语表仅作词汇参考，严禁照搬与当前问题无关的术语，"
            "也不要编造表中不存在的专有名词：\n{glossary}",
        ),
        (
            "human",
            "对话历史：\n{history}\n\n用户最新问题：{question}",
        ),
    ]
)
